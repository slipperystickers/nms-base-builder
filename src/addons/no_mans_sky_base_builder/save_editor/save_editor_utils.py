# extract steam persona names from loginusers.vdf file and return dic of "steam_id":"persona name"
def get_steam_names():
    # it is stored in format like ..."users: { "steam_id" {"PersonaName" "name"} }
    pattern = re.compile(
        r'"(\d+)"\s*{[^}]*"PersonaName"\s*"([^"]+)"',
        re.DOTALL
    )
    steam_names = {}
    steamname_path = get_steamname_path()
    if steamname_path.exists():
        text = steamname_path.read_text(encoding="utf-8")
        for steam_id, persona_name in pattern.findall(text):
            steam_names[str(steam_id)] = persona_name
    return steam_names

#returns list of files with valid save file names within a given folder, parameter is string
def get_hg_files_in_folder(folder):
    hg_files_list = []
    for file in Path(folder).glob("save*.hg"):
        if re.fullmatch(r"save(\d+)?\.hg", file.name):
            hg_files_list.append(file)
    return hg_files_list

#Returns all account folders
def get_accounts_list(context):
    prefs = context.preferences.addons[ADDON_ID].preferences
    save_folder_path = prefs.nms_save_folder_path
    
    steam_names = get_steam_names()
    accounts_list = []
    root_dir = Path(save_folder_path)
    for folder in root_dir.iterdir():
        if not folder.is_dir():
            continue
        # Steam/Gamepass account folders
        if folder.name.startswith("st_"):
            files_list = get_hg_files_in_folder(str(folder))
            account_number = folder.name[3:]
            steam_persona = steam_names.get(account_number,None)
            if files_list is not None:
                if len(files_list) > 0:
                    accounts_list.append({
                        "steam_persona" : steam_persona,
                        "folder"  : folder
                    })
    return accounts_list
    

# Returns list of save slot data that contains save name and save files lines
def get_save_slots_list(account):
    from .save_file import SaveFile
    
    # to validate correct save file name
    pattern = re.compile(r"save(\d+)\.hg")
    # store list of all hg save files
    hg_files_list = get_hg_files_in_folder(account)
    hg_files = set(hg_files_list)
    
    # interate through each save file and record their pairs
    save_slots = []
    for save_2 in hg_files_list:
        match = pattern.fullmatch(save_2.name)
        if not match or int(match.group(1)) % 2:
            continue
        file_number = int(match.group(1))
        save_1_name = "save.hg" if file_number == 2 else f"save{file_number - 1}.hg"
        save_1 = save_2.parent / save_1_name
        if save_1 not in hg_files:
            continue
        save_reader = SaveFile(save_2)
        
        # save type is "Main" for normal save and "Season" for expeditiion
        try:
            save_type = save_reader.search_property(SaveTranslation.active_context)
            if save_type is None:
                continue
        except:
            continue
        
        
        #slot number is always half of second save file's number
        save_slot_number = file_number//2
        #links to save files for this slot
        saves_links = [str(save_1), str(save_2)]
        #extract save's name from save file data by partially loading it, and increasing efficiency
        save_name = save_reader.search_property(SaveTranslation.save_name) if save_type == "Main" else "Expedition"
        
        save_slot = {
            "slot": save_slot_number,
            "saves": saves_links,
            "save_name": save_name or "Un-named"
        }
        save_slots.append(save_slot)
        
    #sort list according to slot number
    save_slots.sort(key=lambda x: x["slot"])
    return save_slots  

# returns list of data related to bses present in a save slot
def _extract_context_bases(save_slot, save_context, save_file=None):
    save_file = save_file or get_save_file(save_slot)
    if save_file.json_data is None:
        save_file.load()
    save_file.context = save_context
    
    obfuscated_persistent_base_data = save_file.get_bases_list_pointer()
    ship_ownsership = save_file.get_ship_ownership_pointer()
    freighter_name = save_file.get_freighter_name()
    
    bases = []
    corvettes = []
    external = []
    freighter = None
    
    space = []
    space_station = []
    
    total_parts_count = 0
    from . import ship_core, ship_repair
    try:
        slot_issues, unassigned = ship_repair.inspect_slots(save_file.json_data, save_context)
    except (ValueError, TypeError, KeyError) as exc:
        slot_issues, unassigned = {}, [str(exc)]
    
    #record only what is necessary rather than entire data about base
    for index,base in enumerate(obfuscated_persistent_base_data):
        if not isinstance(base, dict):
            continue
        
        base_data = BaseData(index, base, ship_ownsership)
        base_data.save_slot = save_slot
        base_data.save_context = save_context
        if base_data.base_type == BaseType.CORVETTE:
            slot = base_data.user_data
            base_data.issues = (tuple(slot_issues.get(slot, ())) if type(slot) is int and 0 <= slot < 12
                                else ('Build has no valid ship slot. Review Link Status in Ship Management.',))
            if not slot_issues and unassigned:
                base_data.issues = tuple(unassigned)
        
        #store list of corvettes and bases in their respective list
        match base_data.base_type :
            case BaseType.CORVETTE:
                corvettes.append(base_data)
            case BaseType.BASE:
                bases.append(base_data)
            case BaseType.FREIGHTER:
                base_data.base_name = freighter_name
                freighter = base_data
            case BaseType.EXTERNAL_BASE:
                if base_data.parts_count > 0:
                    external.append(base_data)
            case BaseType.SPACE_BASE:
                space.append(base_data)
            case BaseType.SPACESTATION_BASE:
                space_station.append(base_data)
        
        if base_data.base_type != BaseType.EXTERNAL_BASE:
            total_parts_count += base_data.parts_count
    
    # sort list of corvettes with restpect to their user_data, because user_data represents location of corvette in ship slots making it wasy to read
    corvettes.sort(key=lambda x: x.user_data if type(x.user_data) is int else 99)
    missing = []
    for index, issues in slot_issues.items():
        if 'Corvette ship has no linked build.' in issues:
            ship = ship_core.ships(save_file.json_data, save_context)[index]
            missing.append(dict(context=save_context, index=index,
                                name=ship_core.get(ship, 'Name') or 'Unnamed', issues=issues))
    
    # return combined list in an object for easy search
    return {
        "corvettes":corvettes,
        "bases":bases,
        "external":external,
        "freighter": freighter,
        "space":space,
        "spacestation":space_station,
        "stations":space_station,
        "total_parts_count": total_parts_count,
        "missing_corvettes": missing,
        "link_warnings": unassigned,
    }
    
    
def extract_bases_list_from_save(save_slot, progress=None):
    sf = get_save_file(save_slot)
    if progress:
        progress.update(.1, f'Loading {sf.path.name}')
    sf.load()
    if progress:
        progress.update(.65, 'Reading bases and Corvettes')
    result = {'corvettes': [], 'bases': [], 'external': [], 'space': [], 'spacestation': [], 'freighters': [], 'freighter': None, 'total_parts_count': 0,
              'source_file': sf.path.name, 'source_mtime': sf.path.stat().st_mtime,
              'source_path': str(sf.path), 'source_hash': sf.source_hash,
              'missing_corvettes': [], 'link_warnings': []}
    for context, key in (('Main', SaveTranslation.base_context), ('Season', SaveTranslation.expedition_context)):
        if progress:
            progress.update(.70 if context == 'Main' else .85,
                            f'Indexing {context} save')
        player = sf.json_data.get(key, {}).get(SaveTranslation.player_state_data, {})
        if not player:
            continue
        data = _extract_context_bases(save_slot, context, sf)
        for name in ('corvettes','bases','external','space','spacestation'):
            result[name].extend(data[name])
        if data['freighter'] is not None:
            result['freighters'].append(data['freighter'])
            if result['freighter'] is None:
                result['freighter'] = data['freighter']
        result['total_parts_count'] += data['total_parts_count']
        result['missing_corvettes'].extend(data['missing_corvettes'])
        result['link_warnings'].extend(data['link_warnings'])
    result['stations'] = result['spacestation']
    return result


# active save is most recently modified save file
def get_lastes_save_file_location(save_slot):
    paths = [Path(p) for p in save_slot if p and Path(p).exists()]
    if not paths:
        raise ValueError('No readable save points in this slot.')
    # Match Ship Management, including deterministic equal-timestamp selection.
    return max(paths, key=lambda p: (p.stat().st_mtime_ns, str(p)))
    
# helper function that gives returns save file object for easier loading
def get_save_file(save_slot):
    save_location = get_lastes_save_file_location(save_slot)
    from .save_file import SaveFile
    save_file = SaveFile(save_location)
    return save_file


# impart a base from save file
def import_paticular_base_from_save(base_identifier, save_slot, progress=None, with_ship_source=False):
    save_file = get_save_file(save_slot)
    if progress:
        progress.update(.1, 'Loading selected save point')
    save_file.load()
    if progress:
        progress.update(.72, 'Finding selected build')
    
    # fist see if base actially exists or not
    searched_base = save_file.search_base_with_identifier(base_identifier)
    if searched_base is None:
        message = (
            "Error importing base"
        )
        ShowMessageBox(message = message, title="Export Failed", icon = "WARNING_LARGE")
        return None
        
    #return bases after translating it to engish
    raw_base = searched_base
    searched_base = save_translation.translate_to_eng_data(searched_base)
    package, source_error = None, ''
    if with_ship_source and base_identifier.base_type == BaseType.CORVETTE:
        from . import ship_package
        try:
            # Capture metadata from the very same read as the imported parts.
            bases = save_file.get_bases_list_pointer()
            actual = [i for i, base in enumerate(bases) if base is raw_base]
            if len(actual) != 1:
                raise ValueError('The imported build is duplicated; use Repair Corvette in I/O.')
            from . import ship_core
            ctx = save_file.context or ship_core.get(save_file.json_data, 'ActiveContext')
            package = ship_package.from_save(save_file.json_data, ctx, actual[0])
        except (ValueError, TypeError, KeyError) as exc:
            source_error = str(exc)
    if progress:
        progress.update(.95, 'Build data ready')

    return (searched_base, package, source_error) if with_ship_source else searched_base
    
#save a base to save file
def save_base_to_save_file(objects_data, base_identifier, save_slot, base_name=None, progress=None, owner_override=None, selected_source=None):
    from .save_file import SaveFile
    from . import ship_files
    save_slot = list(dict.fromkeys(Path(p).resolve() for p in save_slot if p))
    expected = ship_files.export_hashes(save_slot)
    latest = get_lastes_save_file_location(save_slot)
    if selected_source is not None and (
            str(latest) != selected_source.get('source_path')
            or expected[str(latest)] != selected_source.get('source_hash')):
        raise ValueError('The game saved again during export. Click Export to Save to retry.')
    pending = {}
    skipped = []
    total = max(1, len(save_slot))
    for index, slot in enumerate(save_slot):
        if progress is not None:
            progress.update(.15 + .40 * index / total,
                            f'Loading save point {index + 1} / {total}')
        save_file = SaveFile(slot)
        save_file.load()
        
        # look for base in save file to see it it exist or not
        in_base = save_file.search_base_with_identifier(base_identifier)
        if in_base is None:
            # The picker reads the latest save point. The other may predate this base.
            if base_identifier.base_type in BaseType.LOCATED_BASES and slot != latest:
                skipped.append(slot.name)
                continue
            raise ValueError(f'{base_identifier.base_name} was not found in {slot.name}. Refresh the save list and select the base again.')
        if base_identifier.base_type == BaseType.CORVETTE:
            from . import ship_repair, ship_core
            ship_repair.require_objects_destination(save_file.json_data,
                save_file.context or ship_core.get(save_file.json_data, 'ActiveContext'), in_base)
        
        if slot == latest:
            destination_position = in_base.get(SaveTranslation.position)

        # here update objects list with list provided
        in_base[SaveTranslation.objects] = save_translation.translate_to_obf_data(objects_data)
        
        from ..build_metadata import apply_save_owner
        apply_save_owner(in_base, owner_override)

        # update name of base if provided
        if base_name is not None:
            # update name in PersistentPlayerBases
            in_base[SaveTranslation.base_name] = base_name
            
            # update name in ship_ownsership
            if base_identifier.base_type == BaseType.CORVETTE:
                userdata = int(base_identifier.user_data)
                ship_ownsership_element = save_file.get_ship_ownsership_element(userdata)
                ship_ownsership_element[SaveTranslation.base_name] = base_name
        
        pending[Path(slot)] = save_file.json_data
        if progress is not None:
            progress.update(.15 + .40 * (index + 1) / total,
                            f'Prepared save point {index + 1} / {total}')
    ship_files.commit_roots(pending, expected, progress=progress)
    # Older pinned destinations acquire their actual position after a successful write.
    base_identifier.base_position = destination_position
    if progress is not None:
        progress.update(.94, 'Save export finished')
    destination = ", ".join(path.name for path in pending)
    result = f'Saved {len(objects_data)} parts to {destination}.'
    if skipped:
        result += f' {", ".join(skipped)} has no matching base and was left unchanged.'
    return result

# The selected save slot's folder within the shared backup root.
def get_backups_folder(save_links):
    backup_folder = backup_policy.directory(save_links)
    backup_folder.mkdir(parents=True, exist_ok=True)
    return str(backup_folder)

# make backup of both save files linked to a save slot
def backup_save_files(save_links):
    generation, copies = backup_policy.snapshot(save_links, 'manual')
    backup_policy.finish(generation)
    return copies
    
# Open backup for each OS type
def open_backup_folder_in_explorer(save_links):
    backup_folder = Path(get_backups_folder(save_links))

    if not backup_folder.exists():
        print(f"Folder does not exist: {backup_folder}")
        return

    if sys.platform == "win32": #windows
        os.startfile(backup_folder)
    elif sys.platform == "darwin":  # macOS
        subprocess.Popen(["open", str(backup_folder)])
    else:  # Linux
        subprocess.Popen(["xdg-open", str(backup_folder)])
    
